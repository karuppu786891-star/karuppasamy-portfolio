// Generates src/data/brandIcons.ts from the simple-icons package (bundled locally, no CDN).
// Add slugs to the list, then run: node scripts/gen-icons.mjs
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const slugs = [
  "html5","css","javascript","react","nextdotjs","nodedotjs","postgresql",
  "davinciresolve","meta","instagram","claude","googlegemini",
  "typescript","tailwindcss","github","linkedin","gmail","figma","vercel","prisma","git",
];
const bySlug = new Map(Object.values(si).filter((v) => v && v.slug).map((v) => [v.slug, v]));
const out = {};
for (const s of slugs) {
  const icon = bySlug.get(s);
  if (!icon) { console.warn("missing:", s); continue; }
  out[s] = { path: icon.path, hex: icon.hex, title: icon.title };
}
writeFileSync(
  "src/data/brandIcons.ts",
  `// AUTO-GENERATED by scripts/gen-icons.mjs from the "simple-icons" package. Do not edit by hand.\nexport const brandIcons: Record<string, { path: string; hex: string; title: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("wrote", Object.keys(out).length, "icons");
